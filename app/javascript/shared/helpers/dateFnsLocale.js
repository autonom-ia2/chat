/**
 * Returns the date-fns locale for an app locale code (e.g. 'pt_BR').
 * @param {string} [appLocale] - Locale code used by vue-i18n.
 * @returns {Locale} date-fns locale, English when unknown or missing.
 */
export const dateFnsLocaleFor = appLocale =>
  DATE_FNS_LOCALES[appLocale] || enUS;
