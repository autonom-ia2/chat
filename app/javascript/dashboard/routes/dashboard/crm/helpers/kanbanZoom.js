export const normalizeKanbanZoom = value =>
  Number.isInteger(value) &&
  value >= KANBAN_ZOOM_MIN &&
  value <= KANBAN_ZOOM_MAX
    ? value
    : KANBAN_ZOOM_DEFAULT;

